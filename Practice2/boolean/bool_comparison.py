# Boolean comparisons

a = 15
b = 20

print("a =", a, "b =", b)
print("a == b:", a == b) # outputs False because the a and b is not equal
print("a != b:", a != b) # True
print("a > b:", a > b)
print("a < b:", a < b)
print("a >= b:", a >= b)
print("a <= b:", a <= b)

score = 75
passing_score = 60

print("Passed exam:", score >= passing_score)
